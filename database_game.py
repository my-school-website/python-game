def ask_question(item, number, total):
    lesson, question, options, answer = item
    shuffled = list(enumerate(options))
    random.shuffle(shuffled)
    correct_position = next(i + 1 for i, (original, _) in enumerate(shuffled) if original == answer)
    print("\n" + "-" * 62)
    print(lesson)
    print(f"السؤال {number} من {total}")
    print(question)
    for i, (_, text) in enumerate(shuffled, 1):
        print(f"{i}) {text}")
    while True:
        try:
            choice = int(input("اختيارك: "))
            if 1 <= choice <= 4:
                break
        except ValueError:
            pass
        print("❌ أدخل رقمًا من 1 إلى 4.")
    if choice == correct_position:
        print("✅ إجابة صحيحة!")
        return 1
    print(f"❌ إجابة خاطئة. الإجابة الصحيحة: {correct_position}) {shuffled[correct_position - 1][1]}")
    return 0


def run_quiz(count=25):
    selected = random.sample(QUESTIONS, count) if count < len(QUESTIONS) else QUESTIONS.copy()
    random.shuffle(selected)
    score = sum(ask_question(q, i, len(selected)) for i, q in enumerate(selected, 1))
    percent = score / len(selected) * 100
    print("\n" + "=" * 62)
    print(f"🏆 النتيجة: {score} من {len(selected)} ({percent:.0f}%)")
    if percent == 100:
        print("🌟 ممتاز جدًا!")
    elif percent >= 80:
        print("👏 ممتاز!")
    elif percent >= 60:
        print("👍 جيد جدًا، واصل التدريب.")
    else:
        print("📚 راجع الدروس وحاول مرة أخرى.")


def main():
    while True:
        print("\n" + "=" * 62)
