        print("3) خروج")

        choice = input("\nاختيارك: ")

        if choice == "1":
            selected = questions.copy()
            total = 25

        elif choice == "2":
            selected = random.sample(questions, 10)
            total = 10

        elif choice == "3":
            print("\n👋 شكرًا لاستخدام اللعبة.")
            break

        else:
            print("❌ اختيار غير صحيح.")
            continue

        score = start_quiz(selected)

        percentage = (score / total) * 100

        print("\n" + "=" * 60)
        print("                 🏆 النتيجة")
        print("=" * 60)

        print(f"\nدرجتك: {score} من {total}")
        print(f"النسبة المئوية: {percentage:.0f}%")

        if percentage == 100:
            print("🌟 ممتاز جدًا! إجاباتك كلها صحيحة.")
        elif percentage >= 80:
            print("👏 ممتاز! أداء رائع.")
        elif percentage >= 60:
            print("👍 جيد جدًا، استمر في المراجعة.")
        elif percentage >= 50:
            print("🙂 نتيجة جيدة، ولكن تحتاج إلى مزيد من التدريب.")
        else:
            print("📚 حاول مرة أخرى وراجع دروس قواعد البيانات.")

        again = input("\nهل تريد اختبارًا آخر؟ (نعم/لا): ")

