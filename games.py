def start_quiz(selected_questions):
    score = 0

    # خلط ترتيب الأسئلة
    random.shuffle(selected_questions)

    print("\n" + "=" * 60)
    print("             🎮 اختبار قواعد البيانات")
    print("=" * 60)

    for number, q in enumerate(selected_questions, 1):

        print(f"\n{q['lesson']}")
        print(f"\nالسؤال {number} من {len(selected_questions)}")
        print("-" * 60)
        print(q["question"])

        # خلط الاختيارات مع الاحتفاظ بالإجابة الصحيحة
        options = list(enumerate(q["options"]))
        random.shuffle(options)

        correct_position = 0

        for i, (original_index, option) in enumerate(options, 1):
            print(f"{i}) {option}")

            if original_index == q["answer"]:
                correct_position = i

        while True:
            try:
                user_answer = int(input("\nاختر رقم الإجابة: "))

                if 1 <= user_answer <= len(options):
                    break

                print("❌ اختر رقمًا صحيحًا من الخيارات.")

            except ValueError:
                print("❌ الرجاء إدخال رقم فقط.")

        if user_answer == correct_position:
            print("✅ إجابة صحيحة!")
            score += 1
        else:
            print("❌ إجابة خاطئة.")
            print(f"الإجابة الصحيحة هي: {correct_position}")

    return score


